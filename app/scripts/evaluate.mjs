// Evaluation for the project report: node scripts/evaluate.mjs [modelDir] > ../docs/results.md
//  1. Quality + mood metrics per mood and engine (5 seeds each)
//  2. Mood quadrant accuracy (valence/arousal sign of estimate == requested)
//  3. Controllability: correlation between slider value and measured output
//  4. Ablation: shared Conductor plan vs. every instrument with its own plan
import fs from 'node:fs';
import path from 'node:path';
import { ENERGY_PRESETS, makePlan } from '../src/engine/conductor.js';
import { evaluateSong } from '../src/engine/critic.js';
import { INSTRUMENT_ORDER } from '../src/engine/instruments.js';
import { analyzeText, buildSettings, MOOD_ORDER, MOODS } from '../src/engine/moods.js';
import { generateSong } from '../src/engine/pipeline.js';
import { assignRoles, generateTrack } from '../src/engine/procedural.js';
import { GPT } from '../src/engine/gpt.js';
import { Tokenizer } from '../src/engine/tokenizer.js';
import { generateTrackML } from '../src/engine/mlGenerator.js';

const modelDir = process.argv[2] || 'public/models';
let ml = null;
if (fs.existsSync(path.join(modelDir, 'model.json'))) {
  const meta = JSON.parse(fs.readFileSync(path.join(modelDir, 'model.json'), 'utf8'));
  const raw = fs.readFileSync(path.join(modelDir, 'model.bin'));
  const model = new GPT(meta, new Float32Array(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength)));
  const counts = meta.training?.instrument_tracks;
  const trained = counts ? new Set(Object.keys(counts).filter((k) => counts[k] >= 20)) : null;
  ml = { model, tok: new Tokenizer(meta.vocab), trained, meta };
}
const SEEDS = [1, 2, 3, 4, 5];
const DUR = 40;
const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const f = (x, d = 3) => x.toFixed(d);
const pearson = (xs, ys) => {
  const mx = mean(xs);
  const my = mean(ys);
  let n = 0;
  let dx = 0;
  let dy = 0;
  xs.forEach((x, i) => {
    n += (x - mx) * (ys[i] - my);
    dx += (x - mx) ** 2;
    dy += (ys[i] - my) ** 2;
  });
  return n / Math.sqrt(dx * dy || 1);
};

const out = [];
const log = (s = '') => out.push(s);
log('# MoodComposer — evaluation results');
log();
log(`Generated by \`app/scripts/evaluate.mjs\` on ${new Date().toISOString().slice(0, 10)}. ${SEEDS.length} seeds × ${MOOD_ORDER.length} moods, ${DUR}s pieces.`);
if (ml) log(`AI model: ${ml.meta.config.n_layer} layers, d=${ml.meta.config.d_model}, best val loss ${ml.meta.training?.best_val_loss?.toFixed(3)}.`);
log();

// ---------- 1 + 2
const engines = ml ? ['theory', 'hybrid', 'ai'] : ['theory'];
const metricKeys = ['scaleConsistency', 'chordToneOnBeats', 'controlAccuracy', 'structure', 'moodMatch'];
const agg = {};
for (const engine of engines) {
  agg[engine] = { rows: [], quad: 0, n: 0, all: Object.fromEntries(metricKeys.map((k) => [k, []])), score: [] };
  for (const mood of MOOD_ORDER) {
    const vals = Object.fromEntries(metricKeys.map((k) => [k, []]));
    const scores = [];
    for (const seed of SEEDS) {
      const settings = buildSettings(analyzeText(MOODS[mood].label), seed);
      const song = generateSong({ settings, energyPoints: ENERGY_PRESETS[settings.energyShape], duration: DUR, seed, engine, temperature: 1, candidates: engine === 'theory' ? 4 : 1 }, ml);
      const m = song.critic.metrics;
      metricKeys.forEach((k) => {
        vals[k].push(m[k]);
        agg[engine].all[k].push(m[k]);
      });
      scores.push(song.critic.score);
      agg[engine].score.push(song.critic.score);
      const want = MOODS[mood];
      const okV = Math.sign(m.estValence) === Math.sign(want.valence) || Math.abs(want.valence) < 0.1;
      const okA = Math.sign(m.estArousal) === Math.sign(want.arousal) || Math.abs(want.arousal) < 0.1;
      agg[engine].quad += okV && okA ? 1 : 0;
      agg[engine].n++;
    }
    agg[engine].rows.push([mood, ...metricKeys.map((k) => mean(vals[k])), mean(scores)]);
  }
}
for (const engine of engines) {
  log(`## 1. Quality metrics — ${engine} engine`);
  log();
  log(`| Mood | Scale consistency | Chord tones on beats | Control accuracy | Structure | Mood match | Critic score |`);
  log(`|---|---|---|---|---|---|---|`);
  for (const r of agg[engine].rows) log(`| ${MOODS[r[0]].emoji} ${MOODS[r[0]].label} | ${r.slice(1).map((x) => f(x, 2)).join(' | ')} |`);
  log(`| **Mean** | ${metricKeys.map((k) => f(mean(agg[engine].all[k]), 2)).join(' | ')} | ${f(mean(agg[engine].score), 2)} |`);
  log();
}
log('## 2. Mood quadrant accuracy');
log();
log('Share of pieces whose *estimated* valence/arousal (computed from the generated notes) falls in the same quadrant as the requested mood.');
log();
log('| Engine | Accuracy |');
log('|---|---|');
for (const engine of engines) log(`| ${engine} | ${f((100 * agg[engine].quad) / agg[engine].n, 1)}% |`);
log();

// ---------- 3 controllability
log('## 3. Controllability (Pearson r between slider and measured output)');
log();
log('| Control | Instrument | Engine | r |');
log('|---|---|---|---|');
const ctrlEngines = ml ? ['theory', 'ai'] : ['theory'];
for (const engine of ctrlEngines) {
  for (const [ctrl, inst, measure] of [
    ['density', 'piano', (ns, bars) => ns.length / bars],
    ['density', 'drums', (ns, bars) => ns.length / bars],
    ['velocity', 'piano', (ns) => mean(ns.map((n) => n.vel))],
    ['register', 'piano', (ns) => mean(ns.map((n) => n.pitch))],
    ['register', 'violin', (ns) => mean(ns.map((n) => n.pitch))],
  ]) {
    if (engine === 'ai' && ml?.trained && !ml.trained.has(inst)) continue;
    const xs = [];
    const ys = [];
    const values = ctrl === 'register' ? [-2, -1, 0, 1, 2] : [0.1, 0.3, 0.5, 0.7, 0.9];
    for (const v of values) {
      for (const seed of SEEDS) {
        const s = buildSettings(analyzeText('happy'), seed);
        const c = { ...s.instruments[inst], [ctrl]: v, enabled: true };
        const plan = makePlan(s, ENERGY_PRESETS.steady, DUR, seed);
        const role = inst === 'violin' ? 'lead' : inst === 'drums' ? 'drums' : 'harmony';
        const ns = engine === 'ai' ? generateTrackML(ml.model, ml.tok, inst, plan, s, c, seed) : generateTrack(inst, role, plan, s, c, seed);
        if (!ns.length) continue;
        xs.push(v);
        ys.push(measure(ns, plan.bars));
      }
    }
    log(`| ${ctrl} | ${inst} | ${engine} | ${f(pearson(xs, ys), 3)} |`);
  }
}
log();

// ---------- 4 ablation
log('## 4. Ablation — shared Conductor vs. independent instruments');
log();
log('"Independent" = every instrument is generated with its own randomly keyed plan (what happens if you just run separate per-instrument models and layer them). Metrics are measured against the plan of the lead instrument.');
log();
const abl = { shared: { s: [], c: [] }, independent: { s: [], c: [] } };
for (const mood of MOOD_ORDER) {
  for (const seed of SEEDS) {
    const settings = buildSettings(analyzeText(MOODS[mood].label), seed);
    const song = generateSong({ settings, energyPoints: ENERGY_PRESETS[settings.energyShape], duration: DUR, seed, engine: 'theory', candidates: 1 });
    abl.shared.s.push(song.critic.metrics.scaleConsistency);
    abl.shared.c.push(song.critic.metrics.chordToneOnBeats);
    const enabled = INSTRUMENT_ORDER.filter((n) => settings.instruments[n].enabled);
    const { roles } = assignRoles(settings, enabled);
    const tracks = enabled.map((name, i) => {
      const own = { ...settings, key: (settings.key + (i === 0 ? 0 : 1 + ((seed * 7 + i * 5) % 11))) % 12 };
      const plan = makePlan(own, ENERGY_PRESETS[settings.energyShape], DUR, seed + i * 17);
      return { name, role: roles[name], notes: generateTrack(name, roles[name], plan, own, settings.instruments[name], seed + i) };
    });
    const m = evaluateSong({ plan: song.plan, tracks, settings }).metrics;
    abl.independent.s.push(m.scaleConsistency);
    abl.independent.c.push(m.chordToneOnBeats);
  }
}
log('| Setup | Scale consistency | Chord tones on beats |');
log('|---|---|---|');
log(`| Shared Conductor (ours) | ${f(mean(abl.shared.s), 3)} | ${f(mean(abl.shared.c), 3)} |`);
log(`| Independent instruments | ${f(mean(abl.independent.s), 3)} | ${f(mean(abl.independent.c), 3)} |`);
log();
console.log(out.join('\n'));
